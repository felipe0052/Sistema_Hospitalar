DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name = 'AVISOS' AND column_name = 'ID_SETOR';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE AVISOS ADD (ID_SETOR NUMBER REFERENCES SETORES(ID_SETOR) ON DELETE SET NULL)';
        EXECUTE IMMEDIATE 'CREATE INDEX IX_AVISOS_SETOR ON AVISOS (ID_SETOR)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name = 'AVISOS' AND column_name = 'IMAGEM_CAMINHO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE AVISOS ADD (IMAGEM_CAMINHO VARCHAR2(300), IMAGEM_MIME VARCHAR2(50))';
    END IF;

    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name = 'AVISOS' AND column_name = 'IMAGEM_CHAVE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE AVISOS ADD (IMAGEM_CHAVE VARCHAR2(300), IMAGEM_ALT VARCHAR2(200))';
    END IF;
END;
/
