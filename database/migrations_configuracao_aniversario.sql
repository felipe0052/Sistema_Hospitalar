DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'CONFIGURACOES_ANIVERSARIO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE CONFIGURACOES_ANIVERSARIO (
                ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                MENSAGEM      CLOB           NOT NULL,
                TITULO        VARCHAR2(120),
                ASSINATURA    VARCHAR2(150),
                ATUALIZADO_POR NUMBER REFERENCES USUARIOS(ID_USUARIO),
                ATUALIZADO_EM TIMESTAMP
            )
        ';
    END IF;
END;
/
