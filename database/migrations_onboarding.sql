-- ===========================================================================
-- Onboarding digital do novo colaborador
--   * ONBOARDING_ITENS     — checklist do novo colaborador e orientações de primeiros atendimentos
--   * ONBOARDING_PROGRESSO — o que cada colaborador já concluiu
--   * ONBOARDING_CONTATOS  — "quem procurar em cada situação"
-- O mapa do hospital reaproveita SETORES/RAMAIS (guia de ramais por andar).
-- Script idempotente: cria as tabelas só se não existirem e insere o conteúdo
-- inicial só se as tabelas estiverem vazias. O RH/ADMIN edita tudo pela tela.
-- ===========================================================================

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'ONBOARDING_ITENS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE ONBOARDING_ITENS (
                ID_ITEM       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                TITULO        VARCHAR2(150) NOT NULL,
                TIPO          VARCHAR2(20)  DEFAULT ''CHECKLIST'' NOT NULL,
                DESCRICAO     CLOB,
                ORDEM         NUMBER(4)     DEFAULT 0 NOT NULL,
                CRIADO_POR    NUMBER REFERENCES USUARIOS(ID_USUARIO),
                CRIADO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP,
                ATUALIZADO_EM TIMESTAMP,
                CONSTRAINT CK_ONBOARDING_ITENS_TIPO CHECK (TIPO IN (''CHECKLIST'',''ATENDIMENTO''))
            )
        ';
        EXECUTE IMMEDIATE 'CREATE INDEX IX_ONBOARDING_ITENS_ORDEM ON ONBOARDING_ITENS (TIPO, ORDEM)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'ONBOARDING_PROGRESSO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE ONBOARDING_PROGRESSO (
                ID_USUARIO    NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO) ON DELETE CASCADE,
                ID_ITEM       NUMBER NOT NULL REFERENCES ONBOARDING_ITENS(ID_ITEM) ON DELETE CASCADE,
                CONCLUIDO_EM  TIMESTAMP DEFAULT SYSTIMESTAMP,
                CONSTRAINT PK_ONBOARDING_PROGRESSO PRIMARY KEY (ID_USUARIO, ID_ITEM)
            )
        ';
    END IF;

    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'ONBOARDING_CONTATOS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE ONBOARDING_CONTATOS (
                ID_CONTATO    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                SITUACAO      VARCHAR2(200) NOT NULL,
                RESPONSAVEL   VARCHAR2(150) NOT NULL,
                ID_SETOR      NUMBER REFERENCES SETORES(ID_SETOR) ON DELETE SET NULL,
                RAMAL         VARCHAR2(20),
                OBSERVACAO    VARCHAR2(300),
                ORDEM         NUMBER(4)     DEFAULT 0 NOT NULL,
                CRIADO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP,
                ATUALIZADO_EM TIMESTAMP
            )
        ';
    END IF;
END;
