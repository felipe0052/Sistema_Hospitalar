DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'LINKS_ANIVERSARIO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE LINKS_ANIVERSARIO (
                ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                TITULO        VARCHAR2(80)   NOT NULL,
                URL           VARCHAR2(500)  NOT NULL,
                ATIVO         NUMBER(1)      DEFAULT 1 NOT NULL CHECK (ATIVO IN (0,1)),
                CRIADO_POR    NUMBER REFERENCES USUARIOS(ID_USUARIO),
                CRIADO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP,
                ATUALIZADO_EM TIMESTAMP
            )
        ';
    END IF;
END;
/
