-- 1) Prioridade do aviso (carrossel de urgentes)
ALTER TABLE AVISOS ADD (PRIORIDADE VARCHAR2(10) DEFAULT 'NORMAL' NOT NULL);
ALTER TABLE AVISOS ADD CONSTRAINT CK_AVISOS_PRIORIDADE CHECK (PRIORIDADE IN ('NORMAL','URGENTE'));

-- 2) Dados de POP para a base de conhecimento (versão vigente = ATIVO 'S')
ALTER TABLE DOCUMENTOS ADD (
    CODIGO            VARCHAR2(30),                         -- ex.: POP-ENF-012
    JUSTIFICATIVA     VARCHAR2(500),                        -- motivo da nova versão do POP
    RESUMO            CLOB,                               -- pode ser sugerido pela IA na Semana 6
    STATUS_INDEXACAO  VARCHAR2(15) DEFAULT 'PENDENTE' NOT NULL
);
ALTER TABLE DOCUMENTOS ADD CONSTRAINT CK_DOC_STATUS_INDEX
    CHECK (STATUS_INDEXACAO IN ('PENDENTE','PROCESSANDO','INDEXADO','ERRO','SEM_TEXTO'));
CREATE INDEX IX_DOC_ATIVO ON DOCUMENTOS (ATIVO);

-- 3) Trechos dos documentos para a recuperação do RAG (Oracle 23ai: tipo VECTOR)
--    A dimensão do VECTOR deve ser IGUAL à do modelo de embedding (all-MiniLM-L6-v2 = 384).
CREATE TABLE DOCUMENTO_TRECHOS (
    ID_TRECHO  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_DOC     NUMBER NOT NULL REFERENCES DOCUMENTOS(ID_DOC) ON DELETE CASCADE,
    ORDEM      NUMBER NOT NULL,
    PAGINA     NUMBER,
    TEXTO      CLOB NOT NULL,
    EMBEDDING  VECTOR(384, FLOAT32) NOT NULL
);
CREATE INDEX IX_TRECHOS_DOC ON DOCUMENTO_TRECHOS (ID_DOC);

-- 4) Reconhecimentos (criados pelo RH)
CREATE TABLE RECONHECIMENTOS (
    ID_RECONHECIMENTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_COLABORADOR    NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO),
    TIPO              VARCHAR2(20) NOT NULL,
    TITULO            VARCHAR2(200) NOT NULL,
    MENSAGEM          VARCHAR2(2000) NOT NULL,
    ID_AUTOR          NUMBER REFERENCES USUARIOS(ID_USUARIO),
    DATA_CRIACAO      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_RECON_TIPO CHECK (TIPO IN ('PROMOCAO','DESTAQUE','TEMPO_DE_CASA','AGRADECIMENTO'))
);
CREATE INDEX IX_RECON_DATA ON RECONHECIMENTOS (DATA_CRIACAO DESC);

-- 5) Indicações de colegas para reconhecimento (feitas por qualquer usuário, analisadas pelo RH)
CREATE TABLE INDICACOES_RECONHECIMENTO (
    ID_INDICACAO       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_INDICADO        NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO),
    ID_INDICANTE       NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO),
    MOTIVO             VARCHAR2(2000) NOT NULL,
    STATUS             VARCHAR2(10) DEFAULT 'PENDENTE' NOT NULL,
    ID_AVALIADOR       NUMBER REFERENCES USUARIOS(ID_USUARIO),
    ID_RECONHECIMENTO  NUMBER REFERENCES RECONHECIMENTOS(ID_RECONHECIMENTO) ON DELETE SET NULL,
    DATA_INDICACAO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_AVALIACAO     TIMESTAMP,
    CONSTRAINT CK_INDIC_STATUS CHECK (STATUS IN ('PENDENTE','APROVADA','RECUSADA')),
    CONSTRAINT CK_INDIC_PROPRIA CHECK (ID_INDICADO <> ID_INDICANTE)
);
CREATE INDEX IX_INDIC_STATUS ON INDICACOES_RECONHECIMENTO (STATUS, DATA_INDICACAO);

-- 6) Notificações internas: uma linha por publicação (não por usuário).
--    A UNIQUE impede notificação duplicada; EVENTO_DO_DIA usa DATA_REFERENCIA = dia do evento.
CREATE TABLE NOTIFICACOES (
    ID_NOTIFICACAO   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO             VARCHAR2(20) NOT NULL,   -- NOTICIA | EVENTO | EVENTO_DO_DIA | RECONHECIMENTO
    ID_REFERENCIA    NUMBER NOT NULL,         -- ID_AVISO, ID_EVENTO ou ID_RECONHECIMENTO
    DATA_REFERENCIA  DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    TITULO           VARCHAR2(200) NOT NULL,
    DATA_CRIACAO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_NOTIF_TIPO CHECK (TIPO IN ('NOTICIA','EVENTO','EVENTO_DO_DIA','RECONHECIMENTO')),
    CONSTRAINT UQ_NOTIF_REFERENCIA UNIQUE (TIPO, ID_REFERENCIA, DATA_REFERENCIA)
);
CREATE INDEX IX_NOTIF_DATA ON NOTIFICACOES (DATA_CRIACAO DESC);

CREATE TABLE NOTIFICACOES_LIDAS (
    ID_USUARIO      NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO) ON DELETE CASCADE,
    ID_NOTIFICACAO  NUMBER NOT NULL REFERENCES NOTIFICACOES(ID_NOTIFICACAO) ON DELETE CASCADE,
    DATA_LEITURA    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_NOTIF_LIDAS PRIMARY KEY (ID_USUARIO, ID_NOTIFICACAO)
);

-- 7) Log da IA (usado a partir da Semana 6: assistente e sugestão de metadados)
CREATE TABLE LOG_IA (
    ID_LOG        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO    NUMBER REFERENCES USUARIOS(ID_USUARIO),
    OPERACAO      VARCHAR2(20) DEFAULT 'PERGUNTA' NOT NULL,  -- PERGUNTA | ANALISE_POP
    PERGUNTA      VARCHAR2(1000) NOT NULL,
    RESPOSTA      CLOB,
    DOCS_CITADOS  VARCHAR2(500),
    STATUS        VARCHAR2(20) NOT NULL,
    LATENCIA_MS   NUMBER,
    UTIL          CHAR(1),
    DATA_HORA     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_LOG_IA_OPERACAO CHECK (OPERACAO IN ('PERGUNTA','ANALISE_POP')),
    CONSTRAINT CK_LOG_IA_STATUS CHECK (STATUS IN ('OK','SEM_RESULTADO','RECUSADA','INDISPONIVEL','COTA_EXCEDIDA','ERRO'))
);

-- 8) Acesso rápido gerenciado pelo ADMIN (A4 — links externos)
CREATE TABLE ACESSOS_RAPIDOS (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO        VARCHAR2(80)   NOT NULL,
    URL           VARCHAR2(500)  NOT NULL,
    DESCRICAO     VARCHAR2(200),
    ICONE         VARCHAR2(30)   DEFAULT 'compass',
    ORDEM         NUMBER(4)      DEFAULT 0 NOT NULL,
    ATIVO         NUMBER(1)      DEFAULT 1 NOT NULL CHECK (ATIVO IN (0,1)),
    CRIADO_POR    NUMBER REFERENCES USUARIOS(ID_USUARIO),
    CRIADO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP,
    ATUALIZADO_EM TIMESTAMP
);
CREATE INDEX IX_ACESSOS_RAPIDOS_ORDEM ON ACESSOS_RAPIDOS (ATIVO, ORDEM);
