-- ===================== SETORES =====================
CREATE TABLE SETORES (
    ID_SETOR      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME          VARCHAR2(100) NOT NULL,
    ANDAR         VARCHAR2(30),                       -- ex.: 'Térreo', '1º andar'
    DATA_CRIACAO  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX UQ_SETORES_NOME ON SETORES (UPPER(NOME));

-- ===================== RAMAIS =====================
CREATE TABLE RAMAIS (
    ID_RAMAL   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO     VARCHAR2(10) NOT NULL,
    DESCRICAO  VARCHAR2(100),                          -- ex.: 'Posto de enfermagem'
    ID_SETOR   NUMBER NOT NULL REFERENCES SETORES(ID_SETOR) ON DELETE CASCADE,
    CONSTRAINT UQ_RAMAIS_NUMERO UNIQUE (NUMERO),
    CONSTRAINT CK_RAMAIS_NUMERO CHECK (REGEXP_LIKE(NUMERO, '^[0-9]{3,10}$'))
);

-- ===================== USUARIOS =====================
CREATE TABLE USUARIOS (
    ID_USUARIO        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME              VARCHAR2(150) NOT NULL,
    EMAIL             VARCHAR2(150) NOT NULL,
    SENHA_HASH        VARCHAR2(255) NOT NULL,
    ID_SETOR          NUMBER REFERENCES SETORES(ID_SETOR),
    CARGO             VARCHAR2(100),
    DATA_NASCIMENTO   DATE,
    PERFIL            VARCHAR2(20) DEFAULT 'COLABORADOR' NOT NULL,
    STATUS            VARCHAR2(10) DEFAULT 'ATIVO' NOT NULL,
    VERSAO_TOKEN      NUMBER DEFAULT 0 NOT NULL,
    DATA_CRIACAO      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO  TIMESTAMP,
    CONSTRAINT UQ_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_PERFIL CHECK (PERFIL IN ('ADMIN','COLABORADOR','RH','MARKETING')),
    CONSTRAINT CK_USUARIOS_STATUS CHECK (STATUS IN ('ATIVO','INATIVO'))
);

-- ===================== HISTORICO_ACESSO (UC03: registrar data/hora/admin) =====================
CREATE TABLE HISTORICO_ACESSO (
    ID_HISTORICO    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO      NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO),
    ID_ADMIN        NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO),
    CAMPO           VARCHAR2(20) NOT NULL,     -- 'PERFIL' ou 'STATUS'
    VALOR_ANTERIOR  VARCHAR2(20),
    VALOR_NOVO      VARCHAR2(20) NOT NULL,
    DATA_HORA       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_HIST_CAMPO CHECK (CAMPO IN ('PERFIL','STATUS'))
);

-- ===================== AVISOS =====================
CREATE TABLE AVISOS (
    ID_AVISO          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO            VARCHAR2(200) NOT NULL,
    CONTEUDO          CLOB NOT NULL,
    CATEGORIA         VARCHAR2(50) DEFAULT 'COMUNICADO' NOT NULL,
    DESTAQUE          CHAR(1) DEFAULT 'N' NOT NULL,   -- aparece no topo/dashboard
    DATA_PUBLICACAO   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_EXPIRACAO    DATE,                           -- NULL = nunca expira
    DATA_ATUALIZACAO  TIMESTAMP,
    ID_AUTOR          NUMBER REFERENCES USUARIOS(ID_USUARIO),
    CONSTRAINT CK_AVISOS_CATEGORIA CHECK (CATEGORIA IN ('NOTICIA','COMUNICADO','PROMOCAO','MUDANCA_SETOR','DESTAQUE_CORPORATIVO')),
    CONSTRAINT CK_AVISOS_DESTAQUE CHECK (DESTAQUE IN ('S','N'))
);

-- ===================== EVENTOS =====================
CREATE TABLE EVENTOS (
    ID_EVENTO     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO        VARCHAR2(200) NOT NULL,
    DESCRICAO     CLOB,
    CATEGORIA     VARCHAR2(30) DEFAULT 'OUTRO' NOT NULL,
    DATA_INICIO   TIMESTAMP NOT NULL,
    DATA_FIM      TIMESTAMP,
    LOCAL         VARCHAR2(150),
    ID_SETOR      NUMBER REFERENCES SETORES(ID_SETOR),   -- setor organizador (opcional)
    ID_AUTOR      NUMBER REFERENCES USUARIOS(ID_USUARIO),
    DATA_CRIACAO  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_EVENTOS_CATEGORIA CHECK (CATEGORIA IN ('TREINAMENTO','ACAO_INTERNA','INSTITUCIONAL','OUTRO')),
    CONSTRAINT CK_EVENTOS_DATAS CHECK (DATA_FIM IS NULL OR DATA_FIM >= DATA_INICIO)
);

-- ===================== DOCUMENTOS / POPs =====================
CREATE TABLE DOCUMENTOS (
    ID_DOC          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO          VARCHAR2(200) NOT NULL,
    TIPO            VARCHAR2(20) NOT NULL,          -- 'POP' ou 'DOCUMENTO'
    CATEGORIA       VARCHAR2(100),                  -- ex.: 'Enfermagem', 'Farmácia', 'Administrativo'
    DESCRICAO       VARCHAR2(1000),
    PALAVRAS_CHAVE  VARCHAR2(500),                  -- separadas por vírgula
    URL_ARQUIVO     VARCHAR2(500) NOT NULL,         -- caminho/chave no storage
    NOME_ARQUIVO    VARCHAR2(255) NOT NULL,         -- nome original do arquivo
    MIME_TYPE       VARCHAR2(100) NOT NULL,
    TAMANHO_BYTES   NUMBER NOT NULL,
    VERSAO          NUMBER DEFAULT 1 NOT NULL,      -- versionamento automático por tipo+título
    ATIVO           CHAR(1) DEFAULT 'S' NOT NULL,   -- 'S' = versão vigente; só uma por tipo+título
    ID_AUTOR        NUMBER REFERENCES USUARIOS(ID_USUARIO),
    DATA_UPLOAD     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO TIMESTAMP,
    CONSTRAINT CK_DOCUMENTOS_TIPO CHECK (TIPO IN ('POP','DOCUMENTO')),
    CONSTRAINT CK_DOCUMENTOS_ATIVO CHECK (ATIVO IN ('S','N'))
);

-- ===================== FAQS =====================
CREATE TABLE FAQS (
    ID_FAQ        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERGUNTA      VARCHAR2(500) NOT NULL,
    RESPOSTA      CLOB NOT NULL,
    CATEGORIA     VARCHAR2(100) NOT NULL,          -- ex.: 'Férias', 'Benefícios', 'Escalas', 'Normas'
    ORDEM         NUMBER DEFAULT 0 NOT NULL,       -- ordem de exibição dentro da categoria
    ID_AUTOR      NUMBER REFERENCES USUARIOS(ID_USUARIO),
    DATA_CRIACAO  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO TIMESTAMP
);

-- ===================== INTEGRAÇÃO GOOGLE AGENDA (opcional, por colaborador) =====================
CREATE TABLE INTEGRACOES_GOOGLE (
    ID_USUARIO     NUMBER PRIMARY KEY REFERENCES USUARIOS(ID_USUARIO) ON DELETE CASCADE,
    REFRESH_TOKEN  VARCHAR2(1000) NOT NULL,         -- criptografado (Fernet)
    RECEBER_TODOS  CHAR(1) DEFAULT 'N' NOT NULL,    -- 'S' = enviar todos os eventos automaticamente
    DATA_ATIVACAO  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE EVENTOS_GOOGLE (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO       NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO) ON DELETE CASCADE,
    ID_EVENTO        NUMBER NOT NULL REFERENCES EVENTOS(ID_EVENTO) ON DELETE CASCADE,
    GOOGLE_EVENT_ID  VARCHAR2(200) NOT NULL,
    CONSTRAINT UK_EVENTOS_GOOGLE UNIQUE (ID_USUARIO, ID_EVENTO)
);
