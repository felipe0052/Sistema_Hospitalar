ALTER SESSION SET CONTAINER=FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA=DECOS;

CREATE INDEX IX_USUARIOS_SETOR     ON USUARIOS (ID_SETOR);
CREATE INDEX IX_USUARIOS_ANIV      ON USUARIOS (EXTRACT(MONTH FROM DATA_NASCIMENTO), EXTRACT(DAY FROM DATA_NASCIMENTO));
CREATE INDEX IX_RAMAIS_SETOR       ON RAMAIS (ID_SETOR);
CREATE INDEX IX_AVISOS_PUBLICACAO  ON AVISOS (DATA_PUBLICACAO DESC);
CREATE INDEX IX_EVENTOS_INICIO     ON EVENTOS (DATA_INICIO);
CREATE INDEX IX_DOCUMENTOS_TIPO    ON DOCUMENTOS (TIPO, CATEGORIA);
CREATE INDEX IX_FAQS_CATEGORIA     ON FAQS (CATEGORIA, ORDEM);

-- Diretório: só usuários ativos, com setor/andar e ramais concatenados
CREATE OR REPLACE VIEW VW_DIRETORIO AS
SELECT u.ID_USUARIO, u.NOME, u.EMAIL, u.CARGO,
       s.ID_SETOR, s.NOME AS SETOR, s.ANDAR,
       (SELECT LISTAGG(r.NUMERO, ', ') WITHIN GROUP (ORDER BY r.NUMERO)
          FROM RAMAIS r WHERE r.ID_SETOR = s.ID_SETOR) AS RAMAIS
  FROM USUARIOS u
  LEFT JOIN SETORES s ON s.ID_SETOR = u.ID_SETOR
 WHERE u.STATUS = 'ATIVO';
