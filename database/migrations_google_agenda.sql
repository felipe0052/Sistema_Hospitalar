-- ===================== INTEGRAÇÃO GOOGLE AGENDA (opcional, por colaborador) =====================
CREATE TABLE INTEGRACOES_GOOGLE (
    ID_USUARIO     NUMBER PRIMARY KEY REFERENCES USUARIOS(ID_USUARIO) ON DELETE CASCADE,
    REFRESH_TOKEN  VARCHAR2(1000) NOT NULL,         -- criptografado (Fernet)
    RECEBER_TODOS  CHAR(1) DEFAULT 'N' NOT NULL,    -- 'S' = enviar todos os eventos automaticamente
    DATA_ATIVACAO  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE EVENTOS_GOOGLE (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO       NUMBER NOT NULL REFERENCES USUARIOS(ID_USUARIO) ON DELETE CASCADE,
    ID_EVENTO        NUMBER NOT NULL REFERENCES EVENTOS(ID_EVENTO) ON DELETE CASCADE,
    GOOGLE_EVENT_ID  VARCHAR2(200) NOT NULL,
    CONSTRAINT UK_EVENTOS_GOOGLE UNIQUE (ID_USUARIO, ID_EVENTO)
);
