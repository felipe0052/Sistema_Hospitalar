-- Ajuste Pós-Entrega (A4) — Acesso rápido gerenciado pelo ADMIN (links externos)
-- Script idempotente: cria tabela e índice apenas se ainda não existirem.
-- NENHUM link pré-colocado / mock é inserido: os links são geridos pelo ADMIN.
-- ===========================================================================

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'ACESSOS_RAPIDOS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE ACESSOS_RAPIDOS (
                ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                TITULO        VARCHAR2(80)   NOT NULL,
                URL           VARCHAR2(500)  NOT NULL,
                DESCRICAO     VARCHAR2(200),
                ICONE         VARCHAR2(30)   DEFAULT ''compass'',
                ORDEM         NUMBER(4)      DEFAULT 0 NOT NULL,
                ATIVO         NUMBER(1)      DEFAULT 1 NOT NULL CHECK (ATIVO IN (0,1)),
                CRIADO_POR    NUMBER REFERENCES USUARIOS(ID_USUARIO),
                CRIADO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP,
                ATUALIZADO_EM TIMESTAMP
            )
        ';
        EXECUTE IMMEDIATE 'CREATE INDEX IX_ACESSOS_RAPIDOS_ORDEM ON ACESSOS_RAPIDOS (ATIVO, ORDEM)';
    END IF;
END;
/
